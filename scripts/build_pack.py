def ndvi_offset_for_baseline(processing_baseline: str) -> float:
    """BOA_ADD_OFFSET for a Sentinel-2 L2A processing baseline string.

    Baselines >= "04.00" shifted DN by +1000 (ESA's harmonisation change of
    2022-01-25), so BOA reflectance must subtract it back out: BOA = (DN -
    1000) / 10000. Earlier baselines need no correction. Zero-padded
    "NN.NN" strings compare correctly as plain strings.
    """
    return -1000.0 if processing_baseline >= "04.00" else 0.0


def percentile(values: list, pct: float) -> float:
    """Linear-interpolation percentile (matches numpy's default 'linear'
    method) over a list of numbers. `values` need not be pre-sorted.

    Pure Python so it is testable without numpy/rasterio, and is the same
    implementation `ndvi_stats` uses on the (flattened) raster window --
    there is only one percentile rule in this codebase, not a duplicated
    "test" one and a "real" one that could silently diverge.
    """
    ordered = sorted(values)
    n = len(ordered)
    if n == 1:
        return float(ordered[0])
    rank = (pct / 100.0) * (n - 1)
    lo = math.floor(rank)
    hi = math.ceil(rank)
    weight = rank - lo
    return float(ordered[lo] + (ordered[hi] - ordered[lo]) * weight)


def rain_window_dates(date: str) -> tuple:
    """(start, end) ISO date strings for the 7-day-inclusive rain window:
    the scene date plus the 6 previous days."""
    from datetime import date as date_cls, timedelta

    end = date_cls.fromisoformat(date)
    start = end - timedelta(days=6)
    return start.isoformat(), end.isoformat()


def fetch_scene(scene_id: str):
    """STAC search for exactly one Sentinel-2 L2A item, BY SCENE ID.

    Searching by id (not by a datetime window) is deterministic -- one
    request, one result, no pagination/truncation risk. Import is local so
    this module never requires pystac_client to be installed just to be
    imported (e.g. by pytest or --help).
    """
    import pystac_client

    catalog = pystac_client.Client.open(STAC_URL)
    items = list(catalog.search(collections=["sentinel-2-l2a"], ids=[scene_id]).items())
    if not items:
        raise RuntimeError(f"scene not found on STAC ({STAC_URL}): {scene_id}")
    return items[0]


def sign(item):
    """SAS-sign a STAC item's asset hrefs against Planetary Computer
    (anonymous, no API key needed). Import is local -- see module docstring.
    """
    import planetary_computer

    return planetary_computer.sign_item(item)


def ndvi_stats(item, bbox: list) -> Dict[str, Any]:
    """Offset-corrected NDVI stats over `bbox` (WGS84) for a signed item.

    Reads ONLY the AOI window from B04/B08 (never the whole scene), in the
    scene's own CRS (EPSG:32720 for both pinned scenes). Asserts the pixel
    count so a wrong bbox/CRS/resolution fails loudly instead of silently
    shipping a wrong stat.
    """
    import numpy as np
    import rasterio
    from rasterio.warp import transform_bounds
    from rasterio.windows import from_bounds

    baseline = item.properties.get("s2:processing_baseline", "00.00")
    offset = ndvi_offset_for_baseline(baseline)

    def read_window(asset_key: str):
        href = item.assets[asset_key].href
        with rasterio.open(href) as ds:
            if ds.crs.to_epsg() != SCENE_CRS_EPSG:
                raise RuntimeError(
                    f"unexpected scene CRS for {item.id}: EPSG:{ds.crs.to_epsg()} "
                    f"(expected EPSG:{SCENE_CRS_EPSG})"
                )
            left, bottom, right, top = transform_bounds("EPSG:4326", ds.crs, *bbox)
            window = from_bounds(left, bottom, right, top, transform=ds.transform)
            return ds.read(1, window=window).astype("float64")

    red_dn = read_window("B04")
    nir_dn = read_window("B08")

    boa_red = (red_dn + offset) / 10000.0
    boa_nir = (nir_dn + offset) / 10000.0
    denom = boa_nir + boa_red
    with np.errstate(invalid="ignore", divide="ignore"):
        ndvi = np.where(denom == 0, np.nan, (boa_nir - boa_red) / denom)

    valid = ndvi[~np.isnan(ndvi)].flatten().tolist()
    n_pixels = len(valid)
    assert n_pixels == EXPECTED_N_PIXELS, (
        f"expected {EXPECTED_N_PIXELS} pixels for {item.id}, got {n_pixels}"
    )

    return {
        "mean": sum(valid) / n_pixels,
        "median": statistics_median(valid),
        "p10": percentile(valid, 10),
        "p90": percentile(valid, 90),
        "n_pixels": n_pixels,
        "processing_baseline": baseline,
    }


def statistics_median(values: list) -> float:
    """Thin wrapper so ndvi_stats has one obvious import site; kept as a
    plain function (not inlined) so it is trivially mockable in tests."""
    from statistics import median

    return float(median(values))


def rain_7d(lat: float, lon: float, date: str) -> float:
    """Sum of Open-Meteo daily precipitation over the 7-day window ending
    on `date` (inclusive), rounded to 1 decimal. Import is local -- see
    module docstring."""
    import requests

    start, end = rain_window_dates(date)
    resp = requests.get(
        "https://archive-api.open-meteo.com/v1/archive",
        params={
            "latitude": lat,
            "longitude": lon,
            "start_date": start,
            "end_date": end,
            "daily": "precipitation_sum",
            "timezone": RAIN_TIMEZONE,
        },
        timeout=30,
    )
    resp.raise_for_status()
    daily = resp.json()["daily"]["precipitation_sum"]
    return round(sum(v for v in daily if v is not None), 1)


def recompute_measured() -> Dict[str, Dict[str, Any]]:
    """Recompute NDVI stats + 7-day rain for both live presets (fecha_buena,
    fecha_mala) from upstream APIs. Network + rasterio required -- call
    only from --write/--check/--only {ndvi,rain,assemble}."""
    presets = read_json(DATA_DIR / "lote-sentinel-presets.json")
    out: Dict[str, Dict[str, Any]] = {}
    for preset_key, scene_id in SCENES.items():
        preset = presets["presets"][preset_key]
        item = sign(fetch_scene(scene_id))
        out[preset_key] = {
            "ndvi_stats": ndvi_stats(item, AOI_BBOX),
            "rain_mm_7d": rain_7d(CENTER["lat"], CENTER["lon"], preset["date"]),
        }
    return out


