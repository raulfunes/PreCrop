"""Reproduction + audit tool for the PreCrop evidence data pack.

CONFIG constants, JSON I/O with pinned LF line endings, the
"precrop-canon-v1" canonicalisation + sha256 rule, evidence-report
assembly from the committed v2 pack files (data/lote-sentinel-presets.json,
data/demo-scenarios.json, data/photo-point-presets.json), and the Phase 4
reproduction layer: STAC search (by scene id) + SAS signing against
Microsoft Planetary Computer, a windowed rasterio read of B04/B08 over the
AOI bbox, offset-corrected NDVI stats, and Open-Meteo 7-day rain sums.

rasterio / pystac_client / planetary_computer / requests are intentionally
NOT imported at module scope -- each is imported LOCALLY inside the one
function that needs it, so `python scripts/build_pack.py --help`, the
offline `--only evidence` path, and the pytest suite that imports this
module all work on a machine with none of those packages installed. Only
`--write`, `--check` and `--only {ndvi,rain,assemble}` touch the network.

There is no `--fetch-photos` mode: the preset photos under
data/presets/fotos/ are owned by another track and are not generated by
this pack (see data/demo-scenarios.json photos_ownership_note).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"

# ---------------------------------------------------------------------------
# CONFIG - the only place constants live (per design)
# ---------------------------------------------------------------------------

AOI_BBOX = [-63.7254, -31.4245, -63.7146, -31.4155]
CENTER = {"lat": -31.42, "lon": -63.72}

SCENES = {
    "fecha_buena": "S2B_MSIL2A_20250202T140709_R110_T20JML_20250202T175010",
    "fecha_mala": "S2C_MSIL2A_20250207T140811_R110_T20JML_20250207T174511",
}

RAIN_WINDOWS = {
    "fecha_buena": {"start": "2025-01-27", "end": "2025-02-02"},
    "fecha_mala": {"start": "2025-02-01", "end": "2025-02-07"},
}

PINNED_WEEDS = {"bueno": 12, "mixto": 55, "malo": 65}

NDVI_FLOOR = 0.20
NDVI_CEILING = 0.85

WEIGHTS = {"ndvi_norm": 0.6, "climate": 0.25, "weeds_pct": -0.15}

THRESHOLDS = {"verde_min": 70, "amarillo_min": 50, "rojo_below": 50}

CLIMATE_TABLE = [
    {"max_mm": 5, "climate": 25},
    {"max_mm": 15, "climate": 45},
    {"max_mm": 25, "climate": 70},
    {"max_mm": 50, "climate": 90},
    {"max_mm": 80, "climate": 85},
    {"max_mm": None, "climate": 60},
]

CANON_VERSION = "precrop-canon-v1"

STAC_URL = "https://planetarycomputer.microsoft.com/api/stac/v1"
SCENE_CRS_EPSG = 32720  # UTM 20S -- both pinned scenes fall in this zone
EXPECTED_N_PIXELS = 10300  # 103 x 100 px @ 10 m over the AOI bbox
RAIN_TIMEZONE = "America/Argentina/Cordoba"

# --check tolerances. NDVI ±0.002 and rain ±0.2mm come from the design's
# cross-cutting table -- tighter than the spec's ±0.005 NDVI acceptance
# scenario (a stricter NDVI probe can only ever be at least as strict as
# the spec's, never looser), and looser than the spec's literal "rain
# reproduces exactly" (kept as a deliberate deviation: Open-Meteo's archive
# is ERA5-reanalysis-backed and can revise historical days by a fraction of
# a mm on re-fetch; an exact-equality gate would make `--check` flaky
# against a live upstream for a value that is not on the demo path at all).
CHECK_TOLERANCES = {"ndvi": 0.002, "rain_mm": 0.2}


# ---------------------------------------------------------------------------
# I/O helpers
# ---------------------------------------------------------------------------

def read_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def write_json(path: Path, obj: Any) -> None:
    """Write JSON with LF line endings, UTF-8, ensure_ascii=False, trailing newline.

    Windows CRLF would silently change every file's bytes and every git
    diff (see design cross-cutting rules) -- newline="\\n" pins LF
    regardless of the host OS's default.
    """
    text = json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=False)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text + "\n")


# ---------------------------------------------------------------------------
# Canonicalisation - "precrop-canon-v1" (see SOURCES.md / design)
# ---------------------------------------------------------------------------

def _canon_number(value: Any) -> Any:
    """Normalise one payload value so Python and JS serialise it identically.

    Python's `json.dumps` writes an integral float as `100.0`; JS has no
    separate int/float number type, so `JSON.stringify` of the same
    abstract value always writes `100`. Left uncorrected, a scenario whose
    score happened to land on a whole number (or on `-0.0`) would hash
    differently in the Python producer and the TS/JS verifier -- exactly
    the kind of silent cross-language divergence T11/T10 exist to catch.
    `float.is_integer()` is True for `-0.0` too, and `int(-0.0) == 0`, so
    this single check folds both cases into one.
    """
    if isinstance(value, float) and value.is_integer():
        return int(value)
    return value


def canonicalize_payload(payload: Dict[str, Any]) -> str:
    """Serialise a FLAT payload per the precrop-canon-v1 rule.

    Keys sorted ascending by Unicode code point, no whitespace anywhere,
    UTF-8 bytes, ensure_ascii=False (payload values must already be
    ASCII-only strings so this never actually escapes anything). Integral
    floats and -0.0 are coerced to plain ints first -- see `_canon_number`.
    """
    normalised = {k: _canon_number(v) for k, v in payload.items()}
    return json.dumps(
        normalised,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    )


def hash_payload(payload: Dict[str, Any]) -> str:
    canonical = canonicalize_payload(payload)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Scoring helpers (Front owns the formula; the pack only publishes it +
# applies it once to compute expected_score / the evidence report's score)
# ---------------------------------------------------------------------------

def climate_from_rain(rain_mm_7d: float) -> int:
    for rule in CLIMATE_TABLE:
        if rule["max_mm"] is None or rain_mm_7d < rule["max_mm"]:
            return rule["climate"]
    return CLIMATE_TABLE[-1]["climate"]


def ndvi_norm(ndvi: float) -> float:
    value = (ndvi - NDVI_FLOOR) / (NDVI_CEILING - NDVI_FLOOR) * 100
    return max(0.0, min(100.0, value))


def score_from_inputs(ndvi: float, rain_mm_7d: float, weeds_pct: float) -> float:
    n = ndvi_norm(ndvi)
    c = climate_from_rain(rain_mm_7d)
    return (
        WEIGHTS["ndvi_norm"] * n
        + WEIGHTS["climate"] * c
        + WEIGHTS["weeds_pct"] * weeds_pct
    )


def light_for_score(score: float) -> str:
    if score >= THRESHOLDS["verde_min"]:
        return "verde"
    if score >= THRESHOLDS["amarillo_min"]:
        return "amarillo"
    return "rojo"


def score_bp_from_score(score: float) -> int:
    """Integer basis points for Solidity: round HALF-UP, not Python's
    banker's rounding. Python's builtin `round()` rounds .5 ties to the
    nearest EVEN integer (round(0.5) == 0, round(1.5) == 2); JS's
    `Math.round()` always rounds .5 UP. `floor(x + 0.5)` matches Math.round
    for all our positive scores, so Chain's TS client reproduces the same
    integer from the same float without a special case.
    """
    return math.floor(score * 100 + 0.5)


def scene_timestamp_utc(scene_id: str) -> str:
    """Parse the acquisition instant out of a Sentinel-2 scene id.

    e.g. S2B_MSIL2A_20250202T140709_... -> "2025-02-02T14:07:09Z"
    """
    part = scene_id.split("_")[2]
    dt = datetime.strptime(part, "%Y%m%dT%H%M%S").replace(tzinfo=timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


