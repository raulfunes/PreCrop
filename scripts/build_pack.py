def _load_pack_files():
    presets = read_json(DATA_DIR / "lote-sentinel-presets.json")
    scenarios = read_json(DATA_DIR / "demo-scenarios.json")
    points = read_json(DATA_DIR / "photo-point-presets.json")
    return presets, scenarios, points


def _cmd_evidence(write: bool) -> int:
    """Assemble (and optionally write) data/evidence/*.json from the
    already-committed pack files. Offline: no network, no rasterio."""
    presets, scenarios, points = _load_pack_files()
    for scenario_key in scenarios["scenarios"]:
        path = DATA_DIR / "evidence" / f"{scenario_key}.json"
        if write:
            report = build_or_reuse_evidence_report(path, scenario_key, presets, scenarios, points)
            write_json(path, report)
        else:
            report = build_evidence_report(scenario_key, presets, scenarios, points)
        p = report["payload"]
        print(
            f"{scenario_key}: score={p['score']} light={p['light']} "
            f"sha256={report['content_sha256']}"
        )
    return 0


def _cmd_ndvi() -> int:
    """--only ndvi: recompute + print NDVI stats for both live scenes.
    Read-only diagnostic; never writes."""
    for preset_key, scene_id in SCENES.items():
        try:
            stats = ndvi_stats(sign(fetch_scene(scene_id)), AOI_BBOX)
        except Exception as exc:  # network / STAC / rasterio unavailable
            print(f"{preset_key}: UNVERIFIED ({exc})")
            return 2
        print(
            f"{preset_key} ({scene_id}): mean={stats['mean']:.3f} "
            f"median={stats['median']:.3f} p10={stats['p10']:.3f} "
            f"p90={stats['p90']:.3f} n_pixels={stats['n_pixels']}"
        )
    return 0


def _cmd_rain() -> int:
    """--only rain: recompute + print the 7-day rain sum for both scenes'
    dates. Read-only diagnostic; never writes."""
    presets = read_json(DATA_DIR / "lote-sentinel-presets.json")
    for preset_key in SCENES:
        date = presets["presets"][preset_key]["date"]
        try:
            mm = rain_7d(CENTER["lat"], CENTER["lon"], date)
        except Exception as exc:  # network unavailable
            print(f"{preset_key}: UNVERIFIED ({exc})")
            return 2
        print(f"{preset_key} ({date}): rain_mm_7d={mm}")
    return 0


def _cmd_assemble() -> int:
    """--only assemble: recompute NDVI + rain for both scenes and print
    them side by side. Read-only diagnostic (use --write to persist)."""
    try:
        recomputed = recompute_measured()
    except Exception as exc:
        print(f"UNVERIFIED (offline or upstream unreachable): {exc}")
        return 2
    for preset_key, values in recomputed.items():
        stats = values["ndvi_stats"]
        print(
            f"{preset_key}: ndvi_median={stats['median']:.3f} "
            f"ndvi_mean={stats['mean']:.3f} rain_mm_7d={values['rain_mm_7d']}"
        )
    return 0


def _cmd_write() -> int:
    """Regenerate the measured fields in lote-sentinel-presets.json from
    upstream APIs, then rewrite the evidence reports from the refreshed
    presets. Refuses on a dirty presets file so a bad fetch can never
    silently clobber a committed, reviewed value."""
    import subprocess

    dirty = subprocess.run(
        ["git", "status", "--porcelain", "--", "data/lote-sentinel-presets.json"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if dirty.returncode == 0 and dirty.stdout.strip():
        print("refusing --write: data/lote-sentinel-presets.json has uncommitted changes")
        return 1

    try:
        recomputed = recompute_measured()
    except Exception as exc:
        print(f"UNVERIFIED (offline or upstream unreachable): {exc}")
        return 2

    presets = read_json(DATA_DIR / "lote-sentinel-presets.json")
    for preset_key in SCENES:
        preset = presets["presets"][preset_key]
        stats = recomputed[preset_key]["ndvi_stats"]
        preset["ndvi"] = round(stats["median"], 3)
        preset["ndvi_stats"] = {
            "mean": round(stats["mean"], 3),
            "median": round(stats["median"], 3),
            "p10": round(stats["p10"], 3),
            "p90": round(stats["p90"], 3),
            "n_pixels": stats["n_pixels"],
        }
        preset["rain_mm_7d"] = recomputed[preset_key]["rain_mm_7d"]
    write_json(DATA_DIR / "lote-sentinel-presets.json", presets)

    scenarios = read_json(DATA_DIR / "demo-scenarios.json")
    points = read_json(DATA_DIR / "photo-point-presets.json")
    for scenario_key in scenarios["scenarios"]:
        path = DATA_DIR / "evidence" / f"{scenario_key}.json"
        report = build_or_reuse_evidence_report(path, scenario_key, presets, scenarios, points)
        write_json(path, report)

    print("wrote data/lote-sentinel-presets.json and data/evidence/*.json")
    return 0


def _check_field(label: str, published: float, recomputed: float, tolerance: float) -> Dict[str, Any]:
    delta = round(recomputed - published, 6)
    return {
        "label": label,
        "published": published,
        "recomputed": round(recomputed, 6),
        "delta": delta,
        "ok": abs(delta) <= tolerance,
    }


def _cmd_check() -> int:
    """Recompute NDVI + rain from live STAC/Open-Meteo, compare to the
    committed pack values, write NOTHING.

    Exit codes: 0 match (within CHECK_TOLERANCES) - 1 mismatch (prints a
    per-field delta table) - 2 unverified (network/STAC/Open-Meteo
    unreachable; explicitly NOT a failure, so an offline demo-day run of
    this audit-only script does not look broken).
    """
    presets = read_json(DATA_DIR / "lote-sentinel-presets.json")

    try:
        recomputed = recompute_measured()
    except Exception as exc:
        print(f"UNVERIFIED (offline or upstream unreachable): {exc}")
        return 2

    rows = []
    for preset_key in SCENES:
        preset = presets["presets"][preset_key]
        stats = recomputed[preset_key]["ndvi_stats"]
        rows.append(_check_field(
            f"{preset_key}.ndvi_mean", preset["ndvi_stats"]["mean"], stats["mean"],
            CHECK_TOLERANCES["ndvi"],
        ))
        rows.append(_check_field(
            f"{preset_key}.ndvi_median", preset["ndvi_stats"]["median"], stats["median"],
            CHECK_TOLERANCES["ndvi"],
        ))
        rows.append(_check_field(
            f"{preset_key}.rain_mm_7d", preset["rain_mm_7d"], recomputed[preset_key]["rain_mm_7d"],
            CHECK_TOLERANCES["rain_mm"],
        ))

    print(f"{'field':<24}{'published':>12}{'recomputed':>12}{'delta':>10}  ok")
    for r in rows:
        print(f"{r['label']:<24}{r['published']:>12}{r['recomputed']:>12}{r['delta']:>10}  {r['ok']}")

    return 0 if all(r["ok"] for r in rows) else 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="PreCrop evidence pack build/audit tool. Audit-only: "
        "nothing on the demo path calls this script. There is no "
        "--fetch-photos mode -- preset photos are owned by another track."
    )
    parser.add_argument(
        "--only",
        choices=["ndvi", "rain", "assemble", "evidence"],
        default="evidence",
        help="Stage to run (default: evidence). ndvi/rain/assemble are "
        "read-only network diagnostics; evidence assembles (and, with "
        "--write, writes) data/evidence/*.json from the committed pack files.",
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="Persist results. With --only evidence (default): write "
        "data/evidence/*.json from the committed presets (offline). With "
        "--only assemble: regenerate data/lote-sentinel-presets.json and "
        "data/evidence/*.json from upstream APIs (network required).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Recompute NDVI + rain from live STAC/Open-Meteo and compare "
        "to the committed values. Writes nothing. "
        "Exit 0 match, 1 mismatch, 2 unreachable/offline.",
    )
    args = parser.parse_args(argv)

    if args.check:
        return _cmd_check()

    if args.only == "ndvi":
        return _cmd_ndvi()
    if args.only == "rain":
        return _cmd_rain()
    if args.only == "assemble":
        return _cmd_write() if args.write else _cmd_assemble()
    return _cmd_evidence(write=args.write)


if __name__ == "__main__":
    raise SystemExit(main())
